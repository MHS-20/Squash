void deflate_fixed_lengths(uint8_t litlen[288], uint8_t dist[30])
{
    for (int i = 0; i < 288; i++)
        litlen[i] = i < 144 ? 8 : i < 256 ? 9 : i < 280 ? 7 : 8;
    for (int i = 0; i < 30; i++)
        dist[i] = 5;
}
